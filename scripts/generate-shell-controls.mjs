// Writes the Linux and Windows shells' controls tables from contracts/macos-parity.json, so both
// shells offer exactly the inventory's controls with its commands, confirmations and availability
// rules (AC-29). Run it after changing the inventory; the shells' parity tests fail until then.
//
//   scripts/generate-shell-controls.mjs

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const inventory = JSON.parse(readFileSync(join(root, 'contracts/macos-parity.json'), 'utf8'));
const surfaces = { 'Tray menu': 'menu', 'Settings window': 'settings', 'Profile editor': 'editor', 'Log window': 'log', 'About window': 'about', 'Confirmation dialog': 'dialog' };

const controls = inventory.entries
  .filter((e) => !e.helper.part_of)
  .map((e) => ({
    id: e.id,
    surface: surfaces[e.linux.split(':')[0]] ?? 'menu',
    label: e.label,
    command: e.helper.command ?? '',
    commands: e.helper.commands ?? [],
    cancelWorkflow: e.helper.cancel?.workflow ?? '',
    otherwise: e.helper.cancel?.otherwise ?? '',
    shell: e.helper.shell ?? '',
    field: e.helper.field ?? '',
    confirmTitle: e.confirmation?.title ?? '',
    confirmText: e.confirmation?.message ?? '',
    confirmWhen: e.confirmation?.when ?? '',
    choices: e.confirmation?.choices ?? [],
    offeredWhen: e.offered_when ?? '',
    enabledWhen: e.enabled_when ?? '',
  }));

const cpp = (s) => JSON.stringify(s); // a JSON string is a valid C++ and C# string literal here
const header = '// Generated by scripts/generate-shell-controls.mjs from contracts/macos-parity.json. Do not edit.\n';

const linux = header + controls.map((c) =>
  `{${cpp(c.id)}, ${cpp(c.surface)}, ${cpp(c.label)}, ${cpp(c.command)}, {${c.commands.map(cpp).join(', ')}}, ` +
  `${cpp(c.cancelWorkflow)}, ${cpp(c.otherwise)}, ${cpp(c.shell)}, ${cpp(c.field)}, ${cpp(c.confirmTitle)}, ` +
  `${cpp(c.confirmText)}, ${cpp(c.confirmWhen)}, {${c.choices.map(cpp).join(', ')}}, ${cpp(c.offeredWhen)}, ${cpp(c.enabledWhen)}},`).join('\n') + '\n';
writeFileSync(join(root, 'linux/src/parity_controls.inc'), linux);

const windowsDir = join(root, 'windows/src/SSMConnect.App/Shell');
// The Windows table needs the shell's ShellControl record (T61); until then only Linux is written.
if (existsSync(join(windowsDir, 'ShellControl.cs'))) {
  const cs = header + 'namespace SSMConnect.App.Shell;\n\npublic static partial class ParityControls\n{\n    public static IReadOnlyList<ShellControl> All { get; } =\n    [\n' +
    controls.map((c) => `        new(${cpp(c.id)}, ${cpp(c.surface)}, ${cpp(c.label)}, ${cpp(c.command)}, [${c.commands.map(cpp).join(', ')}], ` +
      `${cpp(c.cancelWorkflow)}, ${cpp(c.otherwise)}, ${cpp(c.shell)}, ${cpp(c.field)}, ${cpp(c.confirmTitle)}, ${cpp(c.confirmText)}, ` +
      `${cpp(c.confirmWhen)}, [${c.choices.map(cpp).join(', ')}], ${cpp(c.offeredWhen)}, ${cpp(c.enabledWhen)}),`).join('\n') +
    '\n    ];\n}\n';
  writeFileSync(join(windowsDir, 'ParityControls.g.cs'), cs);
}
console.log(`wrote ${controls.length} controls`);
